export function getItemDisplayName(name: string, language: 'en' | 'vi'): string {
  if (language !== 'en') return name
  const lower = name.toLowerCase().trim()

  for (const def of Object.values(ITEMS_DATABASE)) {
    if (
      lower.includes(def.name.toLowerCase()) ||
      lower.includes(def.enName.toLowerCase()) ||
      def.name.toLowerCase().includes(lower)
    ) {
      return def.enName
    }
  }

  // Common fallbacks
  if (lower.includes('nguyệt đao')) return 'Eclipse'
  if (lower.includes('giáo thiên đường')) return 'Sundered Sky'
  if (lower.includes('vũ điệu tử thần')) return "Death's Dance"
  if (lower.includes('rìu đen')) return 'Black Cleaver'
  if (lower.includes('móng vuốt sterak')) return "Sterak's Gage"
  if (lower.includes('giáp gai')) return 'Thornmail'
  if (lower.includes('khiên doran')) return "Doran's Shield"
  if (lower.includes('kiếm doran')) return "Doran's Blade"
  if (lower.includes('bình máu')) return 'Health Potion'
  if (lower.includes('giày thép gai')) return 'Plated Steelcaps'
  if (lower.includes('giày cuồng nộ')) return "Berserker's Greaves"
  if (lower.includes('giày thần tốc')) return 'Boots of Swiftness'
  if (lower.includes('giày thủy ngân')) return "Mercury's Treads"
  if (lower.includes('kiếm ma youmuu')) return "Youmuu's Ghostblade"
  if (lower.includes('áo choàng bóng tối')) return 'Edge of Night'
  if (lower.includes('collector') || lower.includes('thu thập')) return 'The Collector'
  if (lower.includes('dominik')) return "Lord Dominik's Regards"
  if (lower.includes('vô cực kiếm')) return 'Infinity Edge'
  if (lower.includes('giáp thiên thần')) return 'Guardian Angel'
  if (lower.includes('kiêu hãnh') || lower.includes('hubris')) return 'Hubris'
  if (lower.includes('dao hung tàn')) return 'Serrated Dirk'
  if (lower.includes('mãng xà') || lower.includes('profane')) return 'Profane Hydra'
  if (lower.includes('tiamat')) return 'Tiamat'
  if (lower.includes('nhanh nhẹn') || lower.includes('hearthbound')) return 'Hearthbound Axe'
  if (lower.includes('giày thường') || lower.includes('giày cỏ') || lower === 'giày') return 'Boots'
  if (lower.includes('khoan') || lower.includes('rectrix')) return 'Rectrix'
  if (lower.includes('thức thời') || lower.includes('opportunity')) return 'Opportunity'
  if (lower.includes('ác xà') || lower.includes('serpent')) return "Serpent's Fang"
  if (lower.includes('lời nhắc') || lower.includes('mortal')) return 'Mortal Reminder'
  if (lower.includes('cưa hóa kỹ') || lower.includes('chempunk')) return 'Chempunk Chainsword'
  if (lower.includes('đại bác') || lower.includes('rapid firecannon')) return 'Rapid Firecannon'
  if (lower.includes('chùy gai') || lower.includes('malmortius')) return 'Maw of Malmortius'

  return name
}

export function findItemInfo(name: string): ItemDefinition | null {
  const lower = name.toLowerCase().trim()

  for (const def of Object.values(ITEMS_DATABASE)) {
    if (
      lower.includes(def.name.toLowerCase()) ||
      lower.includes(def.enName.toLowerCase()) ||
      def.name.toLowerCase().includes(lower)
    ) {
      return def
    }
  }

  return null
}
